/* Sitewide search overlay. One copy for every page (styles in assets/css/jesta-search.css).
   Data: assets/js/jesta-search-index.js (generated by tools/search-index/build.js), loaded on demand.
   Pages with the nav bar keep their <button id="jsearch-btn">; pages without one get a floating button.
   Results group by kind with filter chips; the empty state is an invitation with suggestions.
   Keyboard: Ctrl/Cmd+K toggles, Escape closes, arrows move, Enter opens the active (or first) result,
   Tab stays inside the overlay while it is open, focus returns to the opener on close. */
(function () {
  'use strict';
  var INDEX_SRC = '/assets/js/jesta-search-index.js';
  var MAX = 10;
  var CAT_BONUS = { 'Page': 8, 'Game': 8, 'Album Series': 5, 'Album': 5, 'Cartoon Entity': 5, 'One of the Children': 5, 'Merch': 3, 'Blog Post': 3 };
  var SVG = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5" width="15" height="15" aria-hidden="true"><circle cx="11" cy="11" r="7"/><line x1="21" y1="21" x2="15.65" y2="15.65"/></svg>';
  // Copy shown in the overlay. Built-in defaults; Admin > Search Copy can override any field through
  // window.jestaSearchCopy (set before this script runs) or window.jSearchSetCopy(obj) at any time.
  var COPY = {
    placeholder: 'Search the Jestamang universe',
    title: 'Ask the universe',
    line: 'A name, a song, an album, a game. The archive answers as you type.',
    suggestions: ['Kek-B\u016bh', 'Zodiac', 'The Circus Speaks', 'Memory Vault'],
    empty: 'Nothing in the archive answers to that yet.'
  };
  function applyCopy(o) { if (!o) return; ['placeholder', 'title', 'line', 'empty'].forEach(function (k) { if (typeof o[k] === 'string' && o[k].trim()) COPY[k] = o[k].trim(); }); if (Array.isArray(o.suggestions) && o.suggestions.length) COPY.suggestions = o.suggestions.map(String).filter(Boolean); var inp = $('jsearch-input'); if (inp) inp.placeholder = COPY.placeholder; if (isOpen() && !lastQuery.trim()) render(''); }
  applyCopy(window.jestaSearchCopy);
  window.jSearchSetCopy = applyCopy;
  // Result kinds for the group headings and the filter chips; the index category maps onto one of these.
  var KINDS = ['Entities', 'Albums', 'Tracks', 'Videos', 'Games', 'Pages', 'Merch', 'Blog'];
  var CHIP_KINDS = ['Albums', 'Tracks', 'Entities', 'Games', 'Pages'];
  function kindOf(cat) { if (/^Track/.test(cat)) return 'Tracks'; if (/Album/.test(cat)) return 'Albums'; if (/Entity|Children/.test(cat)) return 'Entities'; if (cat === 'Video') return 'Videos'; if (cat === 'Game') return 'Games'; if (cat === 'Page') return 'Pages'; if (cat === 'Merch') return 'Merch'; return 'Blog'; }
  var PER_KIND = 6, kindFilter = 'All', suggestOffset = 0, rotateTimer = null;

  var prepared = null, loading = false, failed = false, attempts = 0, opener = null, active = -1, lastQuery = '', shown = [];

  // ---- text folding: accents, ligatures and apostrophes vanish, everything else lowercases ----
  function foldChar(c) {
    var f = c.toLowerCase();
    try { f = f.normalize('NFKD').replace(/[̀-ͯ]/g, ''); } catch (e) {}
    f = f.replace(/æ/g, 'ae').replace(/œ/g, 'oe').replace(/ø/g, 'o').replace(/ß/g, 'ss').replace(/[’‘'`´]/g, '');
    return f;
  }
  // folded string plus a map from each folded index back to the source character index
  function foldMap(s) {
    var out = '', map = [];
    for (var i = 0; i < s.length; i++) { var f = foldChar(s.charAt(i)); for (var j = 0; j < f.length; j++) { out += f.charAt(j); map.push(i); } }
    return { text: out, map: map };
  }
  var NONWORD = /[^\p{L}\p{N}]+/gu;
  var fold = function (s) { return foldMap(String(s || '')).text; };
  var keyOf = function (s) { return fold(s).replace(NONWORD, ' ').replace(/\s+/g, ' ').trim(); };

  function prepare(idx) {
    return idx.map(function (e, i) {
      var k = keyOf(e.n);
      return { e: e, i: i, k: k, c: k.replace(/ /g, ''), t: keyOf(e.t), cat: String(e.c).split(' – ')[0] };
    });
  }
  function tokens(q) { return keyOf(q).split(' ').filter(Boolean); }
  function score(p, toks, whole) {
    var s = 0;
    for (var i = 0; i < toks.length; i++) {
      var t = toks[i], tc = t.replace(/ /g, ''), got = 0;
      if (p.k === t) got = 100;
      else if (p.k.indexOf(t) === 0) got = 60;
      else if ((' ' + p.k).indexOf(' ' + t) !== -1) got = 40;
      else if (p.k.indexOf(t) !== -1) got = 30;
      else if (tc && p.c.indexOf(tc) !== -1) got = 20;
      if ((' ' + p.t).indexOf(' ' + t) !== -1) got += 12; else if (p.t.indexOf(t) !== -1) got += 10;
      if (!got) return 0;                     // every word of the query has to match somewhere
      s += got;
    }
    if (toks.length > 1 && p.k.indexOf(whole) !== -1) s += 15;
    return s + (CAT_BONUS[p.cat] || 0);
  }
  function search(q) {
    var toks = tokens(q); if (!toks.length || !prepared) return [];
    var whole = toks.join(' '), out = [];
    for (var i = 0; i < prepared.length; i++) { var s = score(prepared[i], toks, whole); if (s > 0) out.push({ p: prepared[i], s: s }); }
    out.sort(function (a, b) { return b.s - a.s || a.p.i - b.p.i; });
    return out;
  }

  // ---- highlight by building DOM nodes, never by string replacement into escaped HTML ----
  function highlightInto(el, name, toks) {
    var fm = foldMap(name), ranges = [];
    toks.forEach(function (t) {
      if (!t) return;
      var from = 0, at;
      while ((at = fm.text.indexOf(t, from)) !== -1) { ranges.push([fm.map[at], fm.map[at + t.length - 1] + 1]); from = at + t.length; }
    });
    ranges.sort(function (a, b) { return a[0] - b[0]; });
    var merged = [];
    ranges.forEach(function (r) { var last = merged[merged.length - 1]; if (last && r[0] <= last[1]) last[1] = Math.max(last[1], r[1]); else merged.push(r.slice()); });
    var pos = 0;
    merged.forEach(function (r) {
      if (r[0] > pos) el.appendChild(document.createTextNode(name.slice(pos, r[0])));
      var m = document.createElement('mark'); m.textContent = name.slice(r[0], r[1]); el.appendChild(m); pos = r[1];
    });
    if (pos < name.length) el.appendChild(document.createTextNode(name.slice(pos)));
  }

  // ---- DOM ----
  function $(id) { return document.getElementById(id); }
  function el(tag, attrs, text) { var n = document.createElement(tag); for (var k in attrs) if (attrs[k] != null) n.setAttribute(k, attrs[k]); if (text != null) n.textContent = text; return n; }
  function ensureOverlay() {
    var o = $('jsearch-overlay'); if (o) return o;
    o = el('div', { id: 'jsearch-overlay', role: 'dialog', 'aria-modal': 'true', 'aria-label': 'Search' });
    var inner = el('div', { id: 'jsearch-inner' });
    var row = el('div', { id: 'jsearch-input-row' });
    var input = el('input', { id: 'jsearch-input', type: 'search', autocomplete: 'off', autocapitalize: 'off', spellcheck: 'false', placeholder: COPY.placeholder, 'aria-label': 'Search', role: 'combobox', 'aria-autocomplete': 'list', 'aria-expanded': 'false', 'aria-controls': 'jsearch-results', 'aria-haspopup': 'listbox' });
    var close = el('button', { id: 'jsearch-close-btn', type: 'button', 'aria-label': 'Close search' }, '✖');
    row.appendChild(input); row.appendChild(close);
    inner.appendChild(row);
    inner.appendChild(el('div', { id: 'jsearch-chips', role: 'group', 'aria-label': 'Filter results by kind' }));
    inner.appendChild(el('div', { id: 'jsearch-status', role: 'status', 'aria-live': 'polite', 'aria-atomic': 'true' }));
    inner.appendChild(el('div', { id: 'jsearch-results', role: 'listbox', 'aria-label': 'Search results' }));
    o.appendChild(inner);
    document.body.appendChild(o);
    return o;
  }
  function ensureButtons() {
    var btn = $('jsearch-btn');
    if (!btn) {
      document.body.classList.add('jsearch-nonav');
      btn = el('button', { type: 'button', 'class': 'jsearch-float-btn', 'aria-label': 'Search' });
      btn.innerHTML = SVG;
      // Game pages have a header row (back link, title, a button on the right): the search sits in that row
      // instead of floating over it. Pages with no header keep the fixed top-right icon.
      var head = document.getElementById('game-header');
      if (head) { btn.classList.add('jsearch-inhead'); head.appendChild(btn); }
      else document.body.appendChild(btn);
    }
    // Pages may carry their own triggers marked data-jsearch (the homepage nav item and grid tile). They all
    // open the overlay; the page's CSS decides which one shows at a given width (the float hides on the
    // homepage desktop, where the nav column item is visible).
    var extra = [].slice.call(document.querySelectorAll('[data-jsearch]'));
    if (extra.length) document.body.classList.add('jsearch-hastrigger');
    [btn].concat(extra).forEach(function (b) {
      if (b.__jsearchWired) return; b.__jsearchWired = true;
      if (!b.hasAttribute('onclick')) b.addEventListener('click', function (e) { e.preventDefault(); toggle(b); });
      b.addEventListener('pointerenter', loadIndex); b.addEventListener('focus', loadIndex);
      b.addEventListener('keydown', function (e) { if (b.tagName === 'A' && (e.key === 'Enter' || e.key === ' ')) { e.preventDefault(); toggle(b); } });
    });
    // the hamburger menu tier hides the nav button: give the menu a Search entry
    var menu = $('jtnav-mobile-overlay');
    if (menu && !$('jtnav-mob-search')) {
      var a = el('a', { id: 'jtnav-mob-search', 'class': 'jtnav-mob-link', href: '#', role: 'button' }, 'Search');
      a.addEventListener('click', function (e) { e.preventDefault(); var c = $('jtnav-mob-close'); if (c) c.click(); setTimeout(function () { open(btn); }, 60); });
      var auth = $('jtnav-mob-auth');
      if (auth) menu.insertBefore(a, auth); else menu.appendChild(a);
    }
    return btn;
  }
  function buttons() { return [].slice.call(document.querySelectorAll('#jsearch-btn,.jsearch-float-btn,[data-jsearch]')); }
  function isOpen() { var o = $('jsearch-overlay'); return !!o && o.classList.contains('jsearch-open'); }

  // ---- index loading (on demand, cached by the service worker) ----
  function loadIndex(cb) {
    if (window.IDX && window.IDX.length) { if (!prepared) prepared = prepare(window.IDX); if (typeof cb === 'function') cb(); return; }
    if (typeof cb === 'function') pendingCbs.push(cb);
    if (loading) return;
    loading = true; failed = false;
    var s = document.createElement('script'); s.src = INDEX_SRC + (attempts++ ? '?r=' + Date.now() : ''); s.async = true;
    s.onload = function () { loading = false; if (window.IDX) prepared = prepare(window.IDX); else failed = true; var cbs = pendingCbs.splice(0); cbs.forEach(function (f) { f(); }); };
    s.onerror = function () { loading = false; failed = true; var cbs = pendingCbs.splice(0); cbs.forEach(function (f) { f(); }); };
    document.head.appendChild(s);
  }
  var pendingCbs = [];

  // ---- render ----
  function setStatus(text) { var st = $('jsearch-status'); if (st && st.textContent !== text) st.textContent = text; }
  function stopRotate() { if (rotateTimer) { clearInterval(rotateTimer); rotateTimer = null; } }
  function reducedMotion() { try { return window.matchMedia('(prefers-reduced-motion: reduce)').matches; } catch (e) { return false; } }
  // The empty state: an invitation and a few suggestions that fill the box when chosen. With more suggestions
  // than fit, the set rotates every few seconds unless the visitor prefers reduced motion.
  function renderWelcome(box) {
    stopRotate();
    var w = el('div', { 'class': 'jsearch-welcome' });
    w.appendChild(el('h3', null, COPY.title));
    w.appendChild(el('p', null, COPY.line));
    var row = el('div', { 'class': 'jsearch-sugg' }); w.appendChild(row);
    var SHOW = 4, list = COPY.suggestions;
    function fill() {
      row.textContent = '';
      for (var n = 0; n < Math.min(SHOW, list.length); n++) {
        var text = list[(suggestOffset + n) % list.length];
        var b = el('button', { type: 'button', 'class': 'jsearch-sugg-btn' }, text);
        b.addEventListener('click', (function (t) { return function () { var inp = $('jsearch-input'); if (!inp) return; inp.value = t; render(t); inp.focus(); }; })(text));
        row.appendChild(b);
      }
    }
    fill();
    if (list.length > SHOW && !reducedMotion()) {
      rotateTimer = setInterval(function () { if (!isOpen() || lastQuery.trim() || !document.body.contains(row)) { stopRotate(); return; } row.classList.add('jsearch-sugg-out'); setTimeout(function () { suggestOffset = (suggestOffset + SHOW) % list.length; fill(); row.classList.remove('jsearch-sugg-out'); }, 260); }, 6000);
    }
    box.appendChild(w);
  }
  function renderChips(kinds) {
    var bar = $('jsearch-chips'); if (!bar) return;
    bar.textContent = '';
    if (!kinds.length) { bar.hidden = true; return; }
    bar.hidden = false;
    var set = ['All'].concat(CHIP_KINDS.filter(function (k) { return kinds.indexOf(k) !== -1; })).concat(kinds.filter(function (k) { return CHIP_KINDS.indexOf(k) === -1; }));
    set.forEach(function (k) {
      var b = el('button', { type: 'button', 'class': 'jsearch-chip', 'aria-pressed': kindFilter === k ? 'true' : 'false' }, k);
      b.addEventListener('click', function () { kindFilter = k; render(lastQuery); var inp = $('jsearch-input'); if (inp) inp.focus(); });
      bar.appendChild(b);
    });
  }
  function render(q) {
    var box = $('jsearch-results'), input = $('jsearch-input'); if (!box) return;
    if (q !== lastQuery) { /* a new query starts unfiltered unless the chosen kind still has results (checked below) */ }
    lastQuery = q; active = -1; shown = [];
    if (input) { input.setAttribute('aria-expanded', 'false'); input.removeAttribute('aria-activedescendant'); }
    box.textContent = '';
    if (!q.trim()) { kindFilter = 'All'; renderChips([]); renderWelcome(box); setStatus(''); return; }
    stopRotate();
    if (!prepared) {
      renderChips([]);
      box.appendChild(el('div', { 'class': 'jsearch-hint' }, failed ? 'THE SEARCH INDEX COULD NOT BE LOADED. CHECK YOUR CONNECTION AND TRY AGAIN.' : 'LOADING THE INDEX\u2026'));
      if (!failed) loadIndex(function () { if (lastQuery === q) render(q); }); else { failed = false; loadIndex(function () { if (lastQuery === q) render(q); }); }
      return;
    }
    var results = search(q);
    if (!results.length) { kindFilter = 'All'; renderChips([]); box.appendChild(el('div', { 'class': 'jsearch-empty' }, COPY.empty)); setStatus('No results'); return; }
    // group by kind, groups in the order their best result scored, a cap per kind when several kinds answer
    var groups = {}, order = [];
    results.forEach(function (r) { var k = kindOf(r.p.cat); if (!groups[k]) { groups[k] = []; order.push(k); } groups[k].push(r); });
    renderChips(order);
    if (kindFilter !== 'All' && !groups[kindFilter]) { kindFilter = 'All'; renderChips(order); }
    var toks = tokens(q), total = 0, hidden = 0, multi = order.length > 1 && kindFilter === 'All';
    order.forEach(function (k) {
      if (kindFilter !== 'All' && k !== kindFilter) { hidden += groups[k].length; return; }
      var list = groups[k], cap = multi ? PER_KIND : (kindFilter !== 'All' ? 40 : MAX); // a chosen kind shows its full list
      var head = el('div', { 'class': 'jsearch-group', role: 'presentation' }, k); box.appendChild(head);
      list.slice(0, cap).forEach(function (r) {
        var e = r.p.e, i = shown.length;
        var a = el('a', { 'class': 'jsearch-item', role: 'option', id: 'jsearch-opt-' + i, href: e.u, 'aria-selected': 'false' });
        a.appendChild(el('span', { 'class': 'jsearch-item-icon', 'aria-hidden': 'true' }, e.i));
        var name = el('span', { 'class': 'jsearch-item-name' }); highlightInto(name, e.n, toks); a.appendChild(name);
        a.appendChild(el('span', { 'class': 'jsearch-item-cat' }, e.c));
        box.appendChild(a); shown.push(a); total++;
      });
      if (list.length > cap) { var moreN = list.length - cap; hidden += moreN; var more = el('button', { type: 'button', 'class': 'jsearch-more-btn' }, moreN + ' more ' + k.toLowerCase()); more.addEventListener('click', (function (kk) { return function () { kindFilter = kk; render(lastQuery); var inp = $('jsearch-input'); if (inp) inp.focus(); }; })(k)); box.appendChild(more); }
    });
    if (input) input.setAttribute('aria-expanded', 'true');
    setStatus(results.length + (results.length === 1 ? ' result' : ' results') + (hidden ? ', showing ' + total : ''));
    updateFade();
  }
  // A soft gradient covers the bottom edge only while more rows sit below the fold.
  function updateFade() { var o = $('jsearch-overlay'); if (!o) return; var more = o.scrollHeight - o.clientHeight > 2 && o.scrollTop + o.clientHeight < o.scrollHeight - 2; o.classList.toggle('jsearch-more-below', more); }
  function setActive(i) {
    if (!shown.length) return;
    if (i < 0) i = shown.length - 1; if (i >= shown.length) i = 0;
    shown.forEach(function (a, j) { a.classList.toggle('jsearch-active', j === i); a.setAttribute('aria-selected', j === i ? 'true' : 'false'); });
    active = i;
    var input = $('jsearch-input'); if (input) input.setAttribute('aria-activedescendant', shown[i].id);
    if (shown[i].scrollIntoView) shown[i].scrollIntoView({ block: 'nearest' });
  }
  function follow(a) { if (!a) return; close(); a.click(); }

  // ---- open / close ----
  function open(from) {
    var o = ensureOverlay(), input = $('jsearch-input');
    if (!o.classList.contains('jsearch-open')) { opener = from || document.activeElement; o.classList.add('jsearch-open'); buttons().forEach(function (b) { b.classList.add('jsearch-active'); b.setAttribute('aria-expanded', 'true'); }); }
    if (input) { input.value = ''; kindFilter = 'All'; render(''); input.focus(); }
    loadIndex();
    updateFade();
  }
  function close() {
    var o = $('jsearch-overlay'); if (!o || !o.classList.contains('jsearch-open')) return;
    o.classList.remove('jsearch-open');
    stopRotate();
    buttons().forEach(function (b) { b.classList.remove('jsearch-active'); b.setAttribute('aria-expanded', 'false'); });
    var visible = function (n) { return !!(n && document.body.contains(n) && n !== document.body && (n.offsetParent !== null || getComputedStyle(n).position === 'fixed')); };
    var back = visible(opener) ? opener : (visible($('jtnav-mobile-toggle')) ? $('jtnav-mobile-toggle') : buttons().filter(visible)[0]);
    opener = null;
    if (back && back.focus) { try { back.focus({ preventScroll: true }); } catch (e) { back.focus(); } }
  }
  function toggle(from) { if (isOpen()) close(); else open(from); }
  window.jSearchOpen = function () { open(); }; window.jSearchClose = close; window.jSearchToggle = toggle;

  // ---- wiring ----
  function focusables() { var o = $('jsearch-overlay'); return o ? [].slice.call(o.querySelectorAll('input,button,a[href]')).filter(function (n) { return n.offsetParent !== null || getComputedStyle(n).position === 'fixed'; }) : []; }
  function init() {
    var o = ensureOverlay(), btn = ensureButtons(), input = $('jsearch-input'), closeBtn = $('jsearch-close-btn');
    buttons().forEach(function (b) { b.setAttribute('aria-expanded', 'false'); b.setAttribute('aria-controls', 'jsearch-overlay'); });
    input.addEventListener('input', function () { render(this.value); });
    o.addEventListener('scroll', updateFade, { passive: true }); window.addEventListener('resize', updateFade);
    closeBtn.addEventListener('click', close);
    input.addEventListener('keydown', function (e) {
      if (e.key === 'ArrowDown') { e.preventDefault(); setActive(active + 1); }
      else if (e.key === 'ArrowUp') { e.preventDefault(); setActive(active - 1); }
      else if (e.key === 'Home' && shown.length && active >= 0) { e.preventDefault(); setActive(0); }
      else if (e.key === 'End' && shown.length && active >= 0) { e.preventDefault(); setActive(shown.length - 1); }
      else if (e.key === 'Enter') { e.preventDefault(); follow(shown[active >= 0 ? active : 0]); }
    });
    $('jsearch-results').addEventListener('keydown', function (e) {
      var items = shown, idx = items.indexOf(document.activeElement);
      if (e.key === 'ArrowDown' && idx >= 0) { e.preventDefault(); items[(idx + 1) % items.length].focus(); }
      else if (e.key === 'ArrowUp' && idx >= 0) { e.preventDefault(); (idx === 0 ? input : items[idx - 1]).focus(); }
    });
    $('jsearch-results').addEventListener('click', function (e) { var a = e.target.closest && e.target.closest('.jsearch-item'); if (a) close(); });
    o.addEventListener('keydown', function (e) {
      if (e.key !== 'Tab') return;
      var f = focusables(); if (!f.length) return;
      var first = f[0], last = f[f.length - 1];
      if (e.shiftKey && document.activeElement === first) { e.preventDefault(); last.focus(); }
      else if (!e.shiftKey && document.activeElement === last) { e.preventDefault(); first.focus(); }
    });
    document.addEventListener('keydown', function (e) {
      if (e.key === 'Escape' && isOpen()) { e.preventDefault(); close(); }
      if ((e.metaKey || e.ctrlKey) && !e.altKey && (e.key === 'k' || e.key === 'K')) { e.preventDefault(); toggle(btn); }
    });
    document.addEventListener('click', function (e) {
      if (!isOpen()) return;
      // composedPath is fixed at dispatch time, so a suggestion or chip that re-rendered itself away still counts as inside
      var path = e.composedPath ? e.composedPath() : [];
      if (o.contains(e.target) || path.indexOf(o) !== -1) return;
      if (buttons().some(function (b) { return b.contains(e.target); })) return;
      var ms = $('jtnav-mob-search'); if (ms && ms.contains(e.target)) return;
      close();
    });
    var idle = window.requestIdleCallback || function (f) { setTimeout(f, 2500); };
    idle(function () { loadIndex(); }, { timeout: 5000 });
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init); else init();
})();
